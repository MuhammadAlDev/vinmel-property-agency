  notary jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index purchases_buyer_idx on public.purchases (buyer_id);

create table public.purchase_steps (
  id bigint generated always as identity primary key,
  purchase_id uuid not null references public.purchases (id) on delete cascade,
  kind text not null check (kind in ('build', 'legal')),
  position int not null default 0,
  title text not null,
  date_text text not null default '',
  state text not null default 'next' check (state in ('done', 'current', 'next')),
  pct int check (pct between 0 and 100),
  note text not null default '',
  doc text not null default '',
  photos jsonb not null default '[]'::jsonb,  -- [{src,label,date}]
  updated_at timestamptz not null default now()
);
create index purchase_steps_idx on public.purchase_steps (purchase_id, kind, position);

-- Tautkan pembelian ke akun pembeli berdasarkan nomor WA / email saat profil dibuat.
create or replace function public.link_purchases_to_profile()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  update public.purchases set buyer_id = new.id
   where buyer_id is null
     and ((new.phone is not null and buyer_phone = new.phone)
       or (new.email is not null and lower(buyer_email) = lower(new.email)));
  return new;
end;
$$;
create trigger profiles_link_purchases
  after insert on public.profiles
  for each row execute function public.link_purchases_to_profile();

