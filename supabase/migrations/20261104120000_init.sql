-- Vinmel Agency: skema awal Supabase
-- Peran: owner (pengelola/CMS) dan buyer (pembeli / user). Semua akun baru = buyer.
-- Owner ditentukan lewat tabel owner_allowlist (email Google atau nomor WA).

create extension if not exists pgcrypto;

-- ───────────── Profil & peran ─────────────
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null default '',
  phone text,            -- format 628xxxxxxxxxx
  email text,
  role text not null default 'buyer' check (role in ('owner', 'buyer')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.owner_allowlist (
  id bigint generated always as identity primary key,
  email text unique,
  phone text unique,
  note text,
  check (email is not null or phone is not null)
);

create or replace function public.is_owner()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'owner');
$$;

-- Buat profil otomatis saat user baru mendaftar (OTP WA / Google).
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_phone text := nullif(new.phone, '');
  v_email text := lower(nullif(new.email, ''));
  v_name text := coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name', '');
  v_role text := 'buyer';
begin
  if exists (select 1 from public.owner_allowlist a
             where (v_email is not null and lower(a.email) = v_email)
                or (v_phone is not null and a.phone = v_phone)) then
    v_role := 'owner';
  end if;
  insert into public.profiles (id, full_name, phone, email, role)
  values (new.id, v_name, v_phone, v_email, v_role)
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Cegah user biasa menaikkan perannya sendiri.
create or replace function public.protect_profile_role()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  -- auth.uid() kosong = service role / SQL editor (boleh).
  if new.role is distinct from old.role and auth.uid() is not null and not public.is_owner() then
    raise exception 'tidak boleh mengubah peran';
  end if;
  new.updated_at := now();
  return new;
end;
$$;

create trigger profiles_protect_role
  before update on public.profiles
  for each row execute function public.protect_profile_role();

-- ───────────── Listing properti ─────────────
create table public.properties (
  id bigint generated by default as identity primary key,
  slug text unique,
  status text not null default 'tayang' check (status in ('draft', 'tayang', 'terjual', 'tersewa', 'arsip')),
  featured boolean not null default false,
  type text not null check (type in ('rumah', 'kos', 'apartemen', 'tanah')),
  deal text not null check (deal in ('Dijual', 'Disewa')),
  title text not null,
  location text not null,          -- contoh: "Bintaro, Tangerang Selatan"
  city text not null,              -- nama kota yang dipakai filter
  province text,
  wilayah_code text,               -- kode kab/kota (BPS/Kemendagri) dari API wilayah
  price_num bigint not null default 0,
  price_label text,                -- contoh "Rp 1,85 M"; kosong = dihitung otomatis
  unit text not null default '',   -- '' | '/bulan' | '/m²'
  lt_num numeric not null default 0,
  lb_num numeric not null default 0,
  kt_num int not null default 0,
  lt_label text, lb_label text, kt_label text, km_label text,
  cert text,
  lat double precision,
  lng double precision,
  photos text[] not null default '{}',
  description text[] not null default '{}',
  fasilitas text[] not null default '{}',
  ext jsonb not null default '{}'::jsonb,   -- detail tambahan sesuai desain (pay, build, facing, ipl, near, dst.)
  source_titip_id uuid,                     -- bila listing berasal dari pengajuan titip
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index properties_filter_idx on public.properties (status, type, deal, city);
create index properties_price_idx on public.properties (price_num);

-- ───────────── Titip properti (pengajuan pemilik) ─────────────
-- stage: 0 review, 1 perlu revisi, 2 survei, 3 approval, 4 disetujui, 5 tayang, 9 ditolak
create table public.titip_submissions (
  id uuid primary key default gen_random_uuid(),
  ref text not null unique,
  user_id uuid references auth.users (id) on delete set null,
  owner_name text not null,
  owner_phone text not null,
  owner_email text,
  submitter_role text not null default 'pemilik' check (submitter_role in ('pemilik', 'kuasa')),
  type text not null check (type in ('rumah', 'kos', 'apartemen', 'tanah')),
  deal text not null check (deal in ('Dijual', 'Disewa')),
  title text not null,
  address text,
  city text,
  price_num bigint,
  plan text not null default 'open' check (plan in ('open', 'eksklusif')),
  payload jsonb not null default '{}'::jsonb,   -- seluruh isian formulir 5 langkah
  photo_paths text[] not null default '{}',      -- path di bucket storage "titip"
  stage int not null default 0 check (stage in (0, 1, 2, 3, 4, 5, 9)),
  review_note text,
  property_id bigint references public.properties (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index titip_user_idx on public.titip_submissions (user_id);
alter table public.properties
  add constraint properties_source_titip_fk foreign key (source_titip_id) references public.titip_submissions (id) on delete set null;

-- ───────────── Pantau properti (pembelian & progres) ─────────────
create table public.purchases (
  id uuid primary key default gen_random_uuid(),
  buyer_id uuid references auth.users (id) on delete set null,
  buyer_phone text,          -- untuk menautkan otomatis bila pembeli belum punya akun
  buyer_email text,
  property_id bigint references public.properties (id) on delete set null,
  title text not null,
  unit text not null default '',
  location text not null default '',
  cover text,
  progress int not null default 0 check (progress between 0 and 100),
  status_text text not null default '',
