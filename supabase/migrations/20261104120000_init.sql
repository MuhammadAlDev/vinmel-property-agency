create policy "profil sendiri atau owner" on public.profiles
  for select using (id = auth.uid() or public.is_owner());
create policy "ubah profil sendiri" on public.profiles
  for update using (id = auth.uid() or public.is_owner()) with check (id = auth.uid() or public.is_owner());

create policy "allowlist hanya owner" on public.owner_allowlist
  for all using (public.is_owner()) with check (public.is_owner());

create policy "listing tayang publik" on public.properties
  for select using (status in ('tayang', 'terjual', 'tersewa') or public.is_owner());
create policy "owner kelola listing" on public.properties
  for all using (public.is_owner()) with check (public.is_owner());

-- Insert titip dilakukan server (service role) agar foto & validasi terkontrol.
create policy "lihat titip sendiri atau owner" on public.titip_submissions
  for select using (user_id = auth.uid() or public.is_owner());
create policy "owner kelola titip" on public.titip_submissions
  for update using (public.is_owner()) with check (public.is_owner());
create policy "owner hapus titip" on public.titip_submissions
  for delete using (public.is_owner());

create policy "pembeli lihat pembelian sendiri" on public.purchases
  for select using (buyer_id = auth.uid() or public.is_owner());
create policy "owner kelola pembelian" on public.purchases
  for all using (public.is_owner()) with check (public.is_owner());

create policy "pembeli lihat progres sendiri" on public.purchase_steps
  for select using (public.is_owner() or exists (
    select 1 from public.purchases p where p.id = purchase_id and p.buyer_id = auth.uid()));
create policy "owner kelola progres" on public.purchase_steps
  for all using (public.is_owner()) with check (public.is_owner());

create policy "favorit sendiri" on public.favorites
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy "survei sendiri atau owner" on public.survey_requests
  for select using (user_id = auth.uid() or public.is_owner());
create policy "buat survei" on public.survey_requests
  for insert with check (user_id is null or user_id = auth.uid());
create policy "owner kelola survei" on public.survey_requests
  for update using (public.is_owner()) with check (public.is_owner());

-- ───────────── Storage ─────────────
-- "listing": foto listing publik. "titip": foto pengajuan, privat (hanya owner via signed URL).
insert into storage.buckets (id, name, public) values ('listing', 'listing', true) on conflict (id) do nothing;
insert into storage.buckets (id, name, public) values ('titip', 'titip', false) on conflict (id) do nothing;

create policy "owner unggah foto listing" on storage.objects
  for insert to authenticated with check (bucket_id = 'listing' and public.is_owner());
create policy "owner ubah foto listing" on storage.objects
  for update to authenticated using (bucket_id = 'listing' and public.is_owner());
create policy "owner hapus foto listing" on storage.objects
  for delete to authenticated using (bucket_id = 'listing' and public.is_owner());
create policy "owner baca foto titip" on storage.objects
  for select to authenticated using (bucket_id = 'titip' and public.is_owner());
