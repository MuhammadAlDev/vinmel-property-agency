  note text,
  status text not null default 'baru' check (status in ('baru', 'dikonfirmasi', 'selesai', 'batal')),
  created_at timestamptz not null default now()
);

-- updated_at otomatis
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$ begin new.updated_at := now(); return new; end; $$;
create trigger properties_touch before update on public.properties for each row execute function public.touch_updated_at();
create trigger titip_touch before update on public.titip_submissions for each row execute function public.touch_updated_at();
create trigger purchases_touch before update on public.purchases for each row execute function public.touch_updated_at();
create trigger purchase_steps_touch before update on public.purchase_steps for each row execute function public.touch_updated_at();

